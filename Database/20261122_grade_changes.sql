BEGIN;
CREATE TABLE IF NOT EXISTS public.grade_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_exam_id integer NOT NULL REFERENCES public.user_exams(id) ON DELETE RESTRICT,
    answer_id integer NOT NULL REFERENCES public.user_exam_answers(id) ON DELETE RESTRICT,
    class_id integer NOT NULL REFERENCES public.course_classes(id) ON DELETE RESTRICT,
    teacher_id integer NOT NULL REFERENCES public.teachers(id) ON DELETE RESTRICT,
    teacher_name text NOT NULL,
    question_text text NOT NULL,
    max_score numeric NOT NULL,
    old_score numeric,
    new_score numeric NOT NULL,
    old_feedback text,
    new_feedback text,
    is_revision boolean NOT NULL,
    reason text CHECK (length(reason) <= 1000),
    changed_at timestamptz NOT NULL DEFAULT now(),
    CHECK (new_score >= 0 AND new_score <= max_score)
);
CREATE INDEX IF NOT EXISTS ix_grade_changes_attempt_id ON public.grade_changes(user_exam_id, id DESC);
-- Access is through the authenticated application backend, not public REST clients.
ALTER TABLE public.grade_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.grade_changes FROM anon, authenticated;
COMMIT;
